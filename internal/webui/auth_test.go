func TestLoginFlowSetsSessionCookie(t *testing.T) {
	s := newTestServer(t, Options{AuthToken: "topsecret"})
	h := s.buildHandler()

	// Wrong token → 401, no cookie.
	rec := httptest.NewRecorder()
	req := httptest.NewRequest(http.MethodPost, "/api/login", strings.NewReader(`{"token":"nope"}`))
	req.Header.Set("Content-Type", "application/json")
	h.ServeHTTP(rec, req)
	if rec.Code != http.StatusUnauthorized {
		t.Fatalf("bad-token login status = %d, want 401", rec.Code)
	}

	// Correct token → 200 + session cookie.
	rec = httptest.NewRecorder()
	req = httptest.NewRequest(http.MethodPost, "/api/login", strings.NewReader(`{"token":"topsecret"}`))
	req.Header.Set("Content-Type", "application/json")
	h.ServeHTTP(rec, req)
	if rec.Code != http.StatusOK {
		t.Fatalf("good-token login status = %d, want 200", rec.Code)
	}
	cookie := sessionCookieFrom(rec.Result().Cookies())
	if cookie == nil {
		t.Fatal("expected session cookie after login")
	}
	if !cookie.HttpOnly || cookie.SameSite != http.SameSiteStrictMode {
		t.Errorf("cookie flags weak: HttpOnly=%v SameSite=%v", cookie.HttpOnly, cookie.SameSite)
	}

	// Cookie authenticates /api/health.
	rec = httptest.NewRecorder()
	req = httptest.NewRequest(http.MethodGet, "/api/health", nil)
	req.AddCookie(cookie)
	h.ServeHTTP(rec, req)
	if rec.Code != http.StatusOK {
		t.Fatalf("authenticated health status = %d, want 200", rec.Code)
	}
	var body map[string]any
	if err := json.Unmarshal(rec.Body.Bytes(), &body); err != nil {
		t.Fatalf("health body: %v", err)
	}
	if body["status"] != "ok" {
		t.Errorf("health status field = %v, want ok", body["status"])
	}
}

