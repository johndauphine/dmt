// newTestServer builds a Server with a fixed token and no port bound.
func newTestServer(t *testing.T, opts Options) *Server {
	t.Helper()
	if opts.Addr == "" {
		opts.Addr = "127.0.0.1:0"
	}
	s, err := New(opts)
	if err != nil {
		t.Fatalf("New: %v", err)
	}
	return s
}

func TestResolveAuthTokenAutoGenerated(t *testing.T) {
	tok, auto, err := resolveAuthToken(Options{Addr: "127.0.0.1:8484"})
	if err != nil {
		t.Fatalf("resolveAuthToken: %v", err)
	}
	if !auto {
		t.Error("expected auto-generated token for empty AuthToken")
	}
	if len(tok) != 64 { // 32 bytes hex
		t.Errorf("token length = %d, want 64", len(tok))
	}
}

func TestResolveAuthTokenExplicit(t *testing.T) {
	tok, auto, err := resolveAuthToken(Options{AuthToken: "  s3cret  "})
	if err != nil {
		t.Fatalf("resolveAuthToken: %v", err)
	}
	if auto {
		t.Error("explicit token should not be marked auto-generated")
	}
	if tok != "s3cret" {
		t.Errorf("token = %q, want trimmed %q", tok, "s3cret")
	}
}

func TestResolveAuthTokenExpandsEnv(t *testing.T) {
	t.Setenv("DMT_TEST_WEBUI_TOKEN", "from-env")
	tok, auto, err := resolveAuthToken(Options{AuthToken: "${env:DMT_TEST_WEBUI_TOKEN}"})
	if err != nil {
		t.Fatalf("resolveAuthToken: %v", err)
	}
	if auto || tok != "from-env" {
		t.Errorf("got token=%q auto=%v, want from-env/false", tok, auto)
	}
}

