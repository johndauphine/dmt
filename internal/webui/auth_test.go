func TestBearerTokenAuth(t *testing.T) {
	s := newTestServer(t, Options{AuthToken: "topsecret"})
	h := s.buildHandler()

	rec := httptest.NewRecorder()
	req := httptest.NewRequest(http.MethodGet, "/api/health", nil)
	req.Header.Set("Authorization", "Bearer topsecret")
	h.ServeHTTP(rec, req)
	if rec.Code != http.StatusOK {
		t.Fatalf("bearer health status = %d, want 200", rec.Code)
	}

	rec = httptest.NewRecorder()
	req = httptest.NewRequest(http.MethodGet, "/api/health", nil)
	req.Header.Set("Authorization", "Bearer wrong")
	h.ServeHTTP(rec, req)
	if rec.Code != http.StatusUnauthorized {
		t.Fatalf("wrong bearer status = %d, want 401", rec.Code)
	}
}

func TestLogoutInvalidatesSession(t *testing.T) {
	s := newTestServer(t, Options{AuthToken: "topsecret"})
	sid, err := s.sessions.create()
	if err != nil {
		t.Fatalf("create session: %v", err)
	}
	if !s.sessions.valid(sid) {
		t.Fatal("session should be valid after create")
	}
	h := s.buildHandler()
	rec := httptest.NewRecorder()
	req := httptest.NewRequest(http.MethodPost, "/api/logout", nil)
	req.AddCookie(&http.Cookie{Name: sessionCookie, Value: sid})
	h.ServeHTTP(rec, req)
	if rec.Code != http.StatusOK {
		t.Fatalf("logout status = %d, want 200", rec.Code)
	}
	if s.sessions.valid(sid) {
		t.Error("session should be invalid after logout")
	}
}

func TestSessionExpiry(t *testing.T) {
	store := newSessionStore(-1 * time.Second) // already expired on create
	sid, err := store.create()
	if err != nil {
		t.Fatalf("create: %v", err)
	}
	if store.valid(sid) {
		t.Error("expired session should not be valid")
	}
}

func sessionCookieFrom(cookies []*http.Cookie) *http.Cookie {
	for _, c := range cookies {
		if c.Name == sessionCookie {
			return c
		}
	}
	return nil
}
